// 섞어 두고 차례로 — 한 바퀴 돌기 전엔 같은 문제가 다시 나오지 않게
let bag = [];

/** 다음 문제 — 너무 쉬운 한 글자 낱말은 빼고 */
export function pickQuiz() {
  if (!bag.length) {
    bag = QUIZ.filter((q) => q.word.length >= 2);
    for (let i = bag.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [bag[i], bag[j]] = [bag[j], bag[i]];
    }
  }
  return bag.pop();
}

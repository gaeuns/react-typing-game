const HANGUL_START = 0xac00;
const isHangulWord = (word) => /^[가-힣]{2,}$/.test(word);

// 게임 낱말 중 명사만 — '달리다' · '행복하다' 같은 동작 · 느낌 낱말과 줄다리기 응원 구호는 뺀다 (명사 '바다'는 사전에 따로 있다)
const NOT_NOUNS = new Set([
  '영차영차', '으라차차', '힘내라', '끝까지', '한번더', '이겨라', '파이팅',
  '아자아자', '가즈아', '버텨라', '밀어붙여', '당겨라', '깡충깡충', '살금살금',
]);
const fromGames = [...GAME_WORD_LISTS.speed.ko, ...GAME_WORD_LISTS.tug.ko, ...GAME_WORD_LISTS.rain.ko].filter(
  (w) => !w.endsWith('다') && !NOT_NOUNS.has(w),
);

/** 끝말잇기에 쓸 수 있는 낱말 전부 */
export const CHAIN_WORDS = new Set([...DICTIONARY.split(/\s+/), ...fromGames].filter(isHangulWord));

// 첫 글자 → 그 글자로 시작하는 낱말들
const BY_FIRST = new Map();
CHAIN_WORDS.forEach((w) => {
  if (!BY_FIRST.has(w[0])) BY_FIRST.set(w[0], []);
  BY_FIRST.get(w[0]).push(w);
});

const syllable = (cho, jung, jong) => String.fromCharCode(HANGUL_START + (cho * 21 + jung) * 28 + jong);

/**
 * 이 글자로 이을 수 있는 첫 글자들 — 두음법칙도 받아 준다.
 * 력 → [력, 역], 로 → [로, 노], 녀 → [녀, 여]
 */
export function startChars(char) {
  const offset = char.charCodeAt(0) - HANGUL_START;
  if (offset < 0 || offset > 11171) return [char];
  const cho = CHO[Math.floor(offset / 588)];
  const jungIndex = Math.floor((offset % 588) / 28);
  const jong = offset % 28;
  const iLike = ['ㅑ', 'ㅕ', 'ㅖ', 'ㅛ', 'ㅠ', 'ㅣ'].includes(JUNG[jungIndex]); // ㅣ나 ㅣ로 시작하는 모음
  if (cho === 'ㄹ') return [char, syllable(CHO.indexOf(iLike ? 'ㅇ' : 'ㄴ'), jungIndex, jong)];
  if (cho === 'ㄴ' && iLike) return [char, syllable(CHO.indexOf('ㅇ'), jungIndex, jong)];
  return [char];
}

/** prev 다음에 word를 이을 수 있는지 (사전 · 이미 쓴 낱말은 따로 본다) */
export const followsChain = (prev, word) => startChars(prev.slice(-1)).includes(word[0]);

/** prev 다음에 올 수 있는 낱말 중 아직 안 쓴 것 */
export function chainAnswers(prev, used) {
  return startChars(prev.slice(-1)).flatMap((c) => BY_FIRST.get(c) ?? []).filter((w) => !used.has(w));
}

/**
 * 타닥이(컴퓨터)가 낼 낱말 — prev가 없으면 아무 데서나 새로 시작.
 * 사람이 받아칠 낱말이 minNext개 이상 남는 것만 고른다 (단계가 오르면 minNext를 줄여 어렵게).
 * 그런 낱말이 없으면 null — 사람이 "한방 단어"로 이긴 것.
 */
export function pickChainWord(prev, used, minNext = 3) {
  const pool = prev ? chainAnswers(prev, used) : [...CHAIN_WORDS].filter((w) => !used.has(w));
  const usedAfter = (w) => new Set(used).add(w);
  const fair = pool.filter((w) => chainAnswers(w, usedAfter(w)).length >= minNext);
  const list = fair.length ? fair : pool.filter((w) => chainAnswers(w, usedAfter(w)).length > 0);
  if (!list.length) return null;
  return list[Math.floor(Math.random() * list.length)];
}
